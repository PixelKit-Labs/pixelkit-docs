// @ts-check
import { existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { satteri } from '@astrojs/markdown-satteri';
import { SITE, BASE, withBase } from './site.config.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CONTENT_DOCS = path.resolve(__dirname, 'src', 'content', 'docs');

/**
 * Human labels for the section slugs `scripts/sync-docs.mjs` writes. A directory not listed here
 * (a brand new `docs/` subdirectory that has not been mapped) still gets a sidebar group — its
 * label just falls back to a title-cased version of its slug — so the sidebar never needs a config
 * edit to pick up new material.
 */
const KNOWN_LABELS = {
  'getting-started': 'Getting Started',
  api: 'API Reference',
  guides: 'Guides',
  'for-coding-agents': 'For Coding Agents',
  project: 'Project',
};

/**
 * Labels for the sections inside `docs/api/`, which are nested a level deeper than the groups above.
 *
 * Starlight's `autogenerate` labels a nested group with its directory name, so these would read
 * "neural-ai" and "pro-exclusives" in the sidebar. The API reference is the part of the site people
 * navigate most, so its groups get written labels.
 */
const API_SECTION_LABELS = {
  'silicon-compute': 'Silicon & Compute',
  'neural-ai': 'Neural & AI',
  'sensors-actuators': 'Sensors & Actuators',
  'radios-security': 'Radios & Security',
  'system-media': 'System & Media',
  'pro-exclusives': 'Pixel Pro Exclusives',
};

/** Preferred left-to-right order; anything else sorts after, alphabetically. */
const ORDER = ['getting-started', 'api', 'guides', 'for-coding-agents', 'project'];

function titleCase(slug) {
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/**
 * Builds the sidebar from whatever section directories `scripts/sync-docs.mjs` actually produced
 * under `src/content/docs/` (itself a mirror of the repo's `docs/` tree — see that script's
 * header comment). Each entry uses Starlight's `autogenerate`, so pages within a section are
 * derived from the directory listing too: add a file under `docs/guides/`, run the sync, and it
 * appears with no change here.
 */
function buildSidebar() {
  if (!existsSync(CONTENT_DOCS)) return [];

  const sections = readdirSync(CONTENT_DOCS, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort((a, b) => {
      const ia = ORDER.indexOf(a);
      const ib = ORDER.indexOf(b);
      if (ia === -1 && ib === -1) return a.localeCompare(b);
      if (ia === -1) return 1;
      if (ib === -1) return -1;
      return ia - ib;
    });

  return sections.map((slug) => ({
    label: KNOWN_LABELS[slug] ?? titleCase(slug),
    items: slug === 'api' ? buildApiItems() : [{ autogenerate: { directory: slug } }],
  }));
}

/**
 * The API group: the index page, then one labelled group per section.
 *
 * Listed explicitly rather than autogenerated so each nested group carries a written label, and so
 * the index sits above the sections instead of being sorted among them. A section directory that
 * appears without a label still shows up, titled from its slug, so adding one needs no edit here.
 */
function buildApiItems() {
  const apiRoot = path.join(CONTENT_DOCS, 'api');
  if (!existsSync(apiRoot)) return [{ autogenerate: { directory: 'api' } }];

  const directories = readdirSync(apiRoot, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name);

  const ordered = [
    ...Object.keys(API_SECTION_LABELS).filter((d) => directories.includes(d)),
    ...directories.filter((d) => !(d in API_SECTION_LABELS)).sort(),
  ];

  return [
    { slug: 'api' },
    ...ordered.map((dir) => ({
      label: API_SECTION_LABELS[dir] ?? titleCase(dir),
      collapsed: true,
      items: [{ autogenerate: { directory: `api/${dir}` } }],
    })),
  ];
}

/**
 * Redirects every page's .md URL to the page itself.
 *
 * The prose is written to be read on GitHub too, so a reader who follows a link from a repository,
 * or types the path they saw in the source tree, arrives at /api/silicon-compute.md and gets a 404.
 * The page exists; only the extension is wrong. Generated from the synced tree rather than
 * hand-listed, so a new page is covered without touching this file.
 */
function buildRedirects() {
  if (!existsSync(CONTENT_DOCS)) return {};
  const out = {};
  const walk = (dir, prefix) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        walk(path.join(dir, entry.name), `${prefix}/${entry.name}`);
        continue;
      }
      if (!/.mdx?$/.test(entry.name)) continue;
      const base = entry.name.replace(/.mdx?$/, '');
      if (base === '404') continue;
      const route = withBase(base === 'index' ? `${prefix}/` : `${prefix}/${base}/`);
      out[`${prefix}/${base}.md`] = route;
    }
  };
  walk(CONTENT_DOCS, '');
  return { ...out, ...RETIRED_ROUTES };
}

/**
 * Pages that were published and then removed, pointed at whatever replaced them.
 *
 * `/api/hardware-api/` was the single page holding all 39 hooks. It is gone: each hook now has its
 * own page, and the two facts that page uniquely carried (the source file path, the verified
 * hardware line) moved onto those pages. The URL was live, so it redirects rather than 404s.
 *
 * The six category URLs are deliberately absent from this list. They still resolve — each is now
 * the section's hub rather than the whole section's prose — so an existing link to
 * `/api/silicon-compute/` still lands somewhere correct.
 */
const RETIRED_ROUTES = {
  '/api/hardware-api': withBase('/api/'),
  '/api/hardware-api.md': withBase('/api/'),
};

/**
 * Wraps every table in a scrolling container.
 *
 * A table needs `overflow-x: auto` so a wide one scrolls instead of pushing the page sideways on a
 * phone. Setting that on the table itself blockifies it: the element then stretches to the content
 * column and takes the border and radius with it, while the rows inside still shrink to fit their
 * text. A narrow table drew a full-width rounded box with the header background and row rules
 * stopping partway across it.
 *
 * Moving the overflow to a wrapper lets the table stay `display: table` and fill its width, so the
 * rows reach the border again.
 *
 * This is a Sätteri hast plugin, not a rehype one: Sätteri is Astro 7's default Markdown processor
 * and does not run the unified pipeline, so `markdown.rehypePlugins` would need
 * `@astrojs/markdown-remark` and would swap the processor for the whole site — including the raw
 * HTML the diagram SVGs are injected as. A filtered visitor returning a replacement node does the
 * same job without changing how anything else is parsed.
 */
const wrapTablesPlugin = {
  name: 'pk-wrap-tables',
  element: {
    filter: ['table'],
    visit(node) {
      // The replacement contains a table, so without this guard the visitor would match its own
      // output and wrap forever.
      if (node.properties?.dataPkWrapped) return;
      return {
        type: 'element',
        tagName: 'div',
        properties: { className: ['pk-table-scroll'] },
        children: [{ ...node, properties: { ...node.properties, dataPkWrapped: 'true' } }],
      };
    },
  },
};

// https://astro.build/config
export default defineConfig({
  site: SITE,
  base: BASE,
  redirects: buildRedirects(),
  markdown: { processor: satteri({ hastPlugins: [wrapTablesPlugin] }) },
  integrations: [
    starlight({
      title: 'PixelKit',
      social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/PixelKit-Labs/pixelkit-sdk' }],
      sidebar: buildSidebar(),
      customCss: ['./src/styles/pixelkit.css', './src/styles/archify.css'],
    }),
  ],
});
